def build(rows, prefix, multi_count):
    documents, questions = [], []
    for i, line in enumerate(rows.strip().splitlines(), 1):
        family, main, exception, literal, paraphrase = line.split("|")
        key = f"{prefix}{i:02}"
        filler = (
            "本条流程记录应记载接收时间、经办人、材料页数和移交对象。记录用于追溯办理过程，不改变本条批准条件、金额标准或适用例外。"
            * 16
            if i <= multi_count
            else "办理记录应按原文件顺序归档。"
        )
        units = {
            key + "A": main,
            key + "C": filler,
            key + "B": exception,
            key
            + "D": "本制度的解释事项由制度维护岗位受理，资料仅用于制度问答，不自动改变比赛财税执行规则。",
        }
        text = f"# {family}制度（合成评测资料）\n\n## 第1条 办理要求\n\n[{key}A] {main}\n\n[{key}C] {filler}\n\n### 例外与限制\n\n[{key}B] {exception}\n\n## 第2条 联系与版本\n\n[{key}D] {units[key + 'D']}\n"
        documents.append(
            {
                "id": key,
                "family": family,
                "title": family + "制度（合成评测资料）",
                "format": "docx" if prefix == "H" and i in (3, 5, 9, 24) else "md",
                "text": text,
                "units": units,
                "grades": {key + "A": 3, key + "B": 3, key + "C": 1, key + "D": 0},
            }
        )
        for j, query in enumerate((literal, paraphrase), 1):
            questions.append(
                {
                    "id": f"{key}Q{j}",
                    "family": family,
                    "query": query,
                    "document": key,
                    "required_units": [key + "A", key + "B"],
                    "answerable": True,
                }
            )
    return documents, questions



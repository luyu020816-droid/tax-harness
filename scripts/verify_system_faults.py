AUTH = Identity("U001")


def rejects(code, fn):
    try:
        fn()
    except AppError as error:
        assert error.code == code, (code, error.as_dict())
        return
    raise AssertionError("Expected " + code)


def stop(child):
    if child.poll() is None:
        subprocess.run(
            ["taskkill", "/PID", str(child.pid), "/T", "/F"],
            capture_output=True,
            check=True,
            creationflags=subprocess.CREATE_NO_WINDOW,
            timeout=10,
        )
    child.wait(timeout=10)


def wait_file(path, child):
    deadline = time.monotonic() + 35
    while not path.exists():
        assert child.poll() is None, "Child failed; inspect its private log"
        assert time.monotonic() < deadline, "No transaction boundary observed"
        time.sleep(0.1)
    return json.loads(path.read_text(encoding="utf-8"))


def main(args):
    args.output = args.output.resolve()
    args.output.mkdir(parents=True, exist_ok=False)
    settings, db = database(Settings(), "development", args.output)
    admin = psycopg.connect(settings.admin_database_url, autocommit=True, row_factory=dict_row)
    envfile = args.output / ".env"
    envfile.write_text(
        "DATABASE_URL="
        + json.dumps(settings.database_url)
        + "\nADMIN_DATABASE_URL="
        + json.dumps(settings.admin_database_url)
        + "\n",
        encoding="utf-8",
    )
    env = {**os.environ, "TAX_HARNESS_ENV_FILE": str(envfile)}
    records = []
    engine = LocalRetrieval(settings.knowledge_model_directory)

    def record(name, **details):
        records.append({"id": name, "pass": True, **details})
        write(args.output / "progress.json", records)
        print(name, "PASS", flush=True)

    try:
        session = create_session(db, AUTH, "C001")
        for mode, invoice, purpose in [
            ("before", "F002", "办公资料整理"),
            ("after", "F003", "办公档案归集"),
            ("read-failure", "F004", "办公凭证整理"),
        ]:
            control = args.output / mode
            control.mkdir()
            turn = accept_turn(
                db, AUTH, str(session["session_id"]), uid(), f"把甲企业{invoice}用途改为{purpose}"
            )
            before = admin.execute(
                "SELECT purpose,revision FROM invoices WHERE company_id='C001' AND invoice_id=%s",
                (invoice,),
            ).fetchone()
            with (control / "worker.log").open("wb") as logfile:
                child = subprocess.Popen(
                    [
                        sys.executable,
                        str(ROOT / "scripts/fault_process_worker.py"),
                        mode,
                        "--control",
                        str(control),
                        "--invoice",
                        invoice,
                        "--purpose",
                        purpose,
                    ],
                    env=env,
                    stdout=logfile,
                    stderr=subprocess.STDOUT,
                    creationflags=subprocess.CREATE_NO_WINDOW,
                )
                try:
                    marker = wait_file(
                        control / ("result.json" if mode == "read-failure" else "boundary.json"),
                        child,
                    )
                    if mode == "before":
                        assert (
                            admin.execute(
                                "SELECT purpose,revision FROM invoices WHERE company_id='C001' AND invoice_id=%s",
                                (invoice,),
                            ).fetchone()
                            == before
                        )
                        assert (
                            admin.execute(
                                "SELECT count(*) AS n FROM operations WHERE source_id=%s",
                                (marker["source_id"],),
                            ).fetchone()["n"]
                            == 0
                        )
                    if mode != "read-failure":
                        stop(child)
                    else:
                        child.wait(timeout=10)
                finally:
                    if child.poll() is None:
                        stop(child)
            meta = json.loads((control / "claimed.json").read_text(encoding="utf-8"))
            current = admin.execute(
                "SELECT purpose,revision FROM invoices WHERE company_id='C001' AND invoice_id=%s",
                (invoice,),
            ).fetchone()
            if mode == "before":
                assert current == before
            else:
                assert current == {"purpose": purpose, "revision": before["revision"] + 1}
            admin.execute(
                "UPDATE work_items SET lease_until=clock_timestamp()-interval '1 second' WHERE work_id=%s",
                (meta["work_id"],),
            )
            runtime = Runtime(db, settings, NoModel())
            takeover = None
            deadline = time.monotonic() + 10
            while takeover is None and time.monotonic() < deadline:
                takeover = runtime.claim()
                if takeover is None:
                    time.sleep(0.1)  # killed backend may still be rolling back
            assert (
                takeover.turn_id == str(turn["turn_id"])
                and takeover.fencing_token > meta["fencing_token"]
            )
            replay = invoice_write.commit(db, AUTH, meta["plan_id"], execution=takeover)
            assert replay["verification_state"] == "verified"
            assert replay["replayed"] == (mode != "before")
            assert (
                admin.execute(
                    "SELECT count(*) AS n FROM operations WHERE source_id=%s", (meta["source_id"],)
                ).fetchone()["n"]
                == 1
            )
            assert (
                admin.execute(
                    "SELECT revision FROM invoices WHERE company_id='C001' AND invoice_id=%s",
                    (invoice,),
                ).fetchone()["revision"]
                == before["revision"] + 1
            )
            if mode == "read-failure":
                assert (
                    marker["commit_state"] == "committed"
                    and marker["verification_state"] == "pending"
                )
                assert (
                    verify_operation(db, AUTH, str(marker["operation_id"]))["verification_state"]
                    == "verified"
                )
            # Reconstruct the old execution token and prove it cannot run late.
            from dataclasses import replace

            stale = replace(takeover, fencing_token=meta["fencing_token"])

            def late(stale=stale):
                with db.transaction() as conn:
                    guard(conn, stale)

            rejects("SOURCE_INVALIDATED", late)
            admin.execute(
                "UPDATE work_items SET state='done',lease_until=NULL WHERE work_id=%s",
                (meta["work_id"],),
            )
            admin.execute(
                "UPDATE turns SET status='completed' WHERE turn_id=%s", (meta["turn_id"],)
            )
            record(
                mode + "_kill_or_connection_loss",
                invoice=invoice,
                operation_id=str(replay["operation_id"]),
            )

        store = Knowledge(db, settings)
        jobs = KnowledgeJobs(db, settings, engine)
        retrieval = KnowledgeRetrieval(db, settings, engine)
        text = "内部资料不得直接外发。例外：经书面批准后可以提供脱敏汇总表，但不得公开客户手机号。"
        doc = store.upload(
            AUTH,
            name="故障演练制度.txt",
            content=text.encode(),
            company_id="C001",
            title="资料外发制度",
            request_id=uid(),
        )
        job = jobs.claim()
        assert str(job["job_id"]) == doc["job_id"]
        jobs.run(job)
        assert store.job(AUTH, doc["job_id"])["state"] == "done"
        with admin.transaction():
            publish_company(
                admin,
                doc["document_id"],
                doc["version_id"],
                store.get(AUTH, doc["document_id"])["revision"],
                uid(),
            )
        result = retrieval.search(
            Identity("U002"),
            company_id="C001",
            query="内部资料可以直接外发吗，需要什么批准？",
            document_ids=[doc["document_id"]],
        )
        assert result["evidence"]
        citation = result["evidence"][0]["citation_id"]
        with admin.transaction():
            revoke_read(admin, "U002", "C001", uid())
        rejects("RESOURCE_NOT_FOUND", lambda: retrieval.read(Identity("U002"), citation))
        record("in_flight_scope_revocation")
        private = store.upload(
            AUTH,
            name="旧任务.txt",
            content="旧任务不得在接管后发布。".encode(),
            company_id="C001",
            title="租约测试",
            request_id=uid(),
        )
        old = jobs.claim()
        assert str(old["job_id"]) == private["job_id"]
        admin.execute(
            "UPDATE retrieval_jobs SET lease_until=clock_timestamp()-interval '1 second' WHERE job_id=%s",
            (old["job_id"],),
        )
        newer = jobs.claim()
        assert newer["fencing_token"] > old["fencing_token"]
        rejects("SOURCE_INVALIDATED", lambda: jobs.stage(old, "parsing"))
        parsed = extract("旧任务不得在接管后发布。".encode(), ".txt")
        chunks = chunk_blocks(parsed["blocks"], "租约测试", engine.count)
        vectors = engine.embed([c["retrieval_text"] for c in chunks])
        profile, manifest = engine.profile()
        rejects(
            "SOURCE_INVALIDATED",
            lambda: jobs.publish(old, parsed, chunks, vectors, profile, manifest),
        )
        jobs.run(newer)
        assert store.job(AUTH, private["job_id"])["state"] == "done"
        record("late_index_publish_fenced")
        missing_engine = LocalRetrieval(args.output / "missing-models")
        try:
            unavailable = KnowledgeRetrieval(db, settings, missing_engine)
            assert not unavailable.ready()["ready"]
            degraded = unavailable.search(
                AUTH, company_id="C001", query="内部资料外发", document_ids=[doc["document_id"]]
            )
            assert (
                degraded["status"] == "unavailable"
                and degraded["retrieval_mode"] == "unavailable"
                and degraded["degraded_reason"] == "DEPENDENCY_UNAVAILABLE"
                and not degraded["evidence"]
            ), degraded
            assert (
                str(business.query_month(db, AUTH, "C001", "2026-09")["invoice_total"]) == "9622.06"
            )
        finally:
            missing_engine.close()
        record("missing_embedding_is_visible_business_stays_available")
        rule = admin.execute(
            "SELECT r.* FROM rule_versions r JOIN rule_scopes s USING(rule_version_id) WHERE s.company_id='C001' AND (SELECT count(*) FROM rule_scopes x WHERE x.rule_version_id=r.rule_version_id)=1 ORDER BY r.effective_from DESC LIMIT 1"
        ).fetchone()
        assert rule
        rule_doc = store.upload(
            AUTH,
            name="生效规则原文.txt",
            content=rule["full_text"].encode(),
            company_id="C001",
            title="生效规则依据",
            request_id=uid(),
        )
        jobs.run(jobs.claim())
        with admin.transaction():
            publish_company(
                admin,
                rule_doc["document_id"],
                rule_doc["version_id"],
                store.get(AUTH, rule_doc["document_id"])["revision"],
                uid(),
            )
            anchor = admin.execute(
                "SELECT block_id FROM knowledge_blocks WHERE version_id=%s",
                (rule_doc["version_id"],),
            ).fetchone()
            link_rule(
                admin,
                str(rule["rule_version_id"]),
                [
                    {
                        "knowledge_version_id": rule_doc["version_id"],
                        "block_id": str(anchor["block_id"]),
                    }
                ],
                uid(),
            )
        record("active_rule_knowledge_link")
        preference = change_preference(
            db, AUTH, action="remember", key="response_style", value="保留依据", request_id=uid()
        )
        change_task(
            db,
            AUTH,
            action="start",
            company_id="C001",
            period="2026-09",
            intent="complete_purposes",
            request_id=uid(),
        )
        history = HistoryJobs(db, settings, engine)
        while claimed := history.claim():
            history.run(claimed)
        # Include real OCR output and raw file bytes in the full-state backup.
        if args.ocr_evaluation:
            from psycopg.conninfo import make_conninfo

            source_name = (
                "tax_harness_retrieval_dev_v1_" + digest(str(args.ocr_evaluation.resolve()))[:8]
            )
            with psycopg.connect(
                make_conninfo(settings.admin_database_url, dbname=source_name), row_factory=dict_row
            ) as source:
                raw = source.execute(
                    "SELECT f.file_bytes FROM knowledge_files f WHERE f.original_name='mixed.pdf' ORDER BY f.created_at LIMIT 1"
                ).fetchone()
            assert raw
            ocr = store.upload(
                AUTH,
                name="mixed.pdf",
                content=bytes(raw["file_bytes"]),
                company_id="C001",
                title="扫描原件恢复样本",
                request_id=uid(),
            )

            async def index_ocr():
                await jobs.start()
                try:
                    for _ in range(1500):
                        state = store.job(AUTH, ocr["job_id"])
                        if state["state"] in ("done", "failed", "blocked"):
                            break
                        await asyncio.sleep(0.5)
                    assert state["state"] == "done", state
                finally:
                    await jobs.stop()

            asyncio.run(index_ocr())
            assert (
                admin.execute(
                    "SELECT count(*) AS n FROM knowledge_blocks WHERE version_id=%s AND locator->>'extraction'='ocr'",
                    (ocr["version_id"],),
                ).fetchone()["n"]
                > 0
            )
            record("scanned_file_and_index_for_recovery", version_id=ocr["version_id"])
        recovery.backup(settings.admin_database_url, args.output / "older")
        with admin.transaction():
            assert admin.execute(
                "SELECT can_read FROM user_company_grants WHERE user_id='U001' AND company_id='C002'"
            ).fetchone()["can_read"]
            revoke_read(admin, "U001", "C002", uid())
        current = store.get(AUTH, private["document_id"])
        store.change(
            AUTH,
            private["document_id"],
            action="disable",
            expected_revision=current["revision"],
            request_id=uid(),
        )
        change_preference(
            db,
            AUTH,
            action="delete",
            target_id=str(preference["preference_id"]),
            expected_revision=preference["revision"],
            request_id=uid(),
        )
        # A fresh, authorized write must not become replayable after recovery.
        session2 = create_session(db, AUTH, "C001")
        accept_turn(
            db, AUTH, str(session2["session_id"]), uid(), "把甲企业F005用途改为办公资料备份"
        )
        ex = Runtime(db, settings, NoModel()).claim()
        with db.transaction(readonly=True) as conn:
            src = conn.execute(
                "SELECT * FROM sources WHERE source_id=%s", (ex.source_id,)
            ).fetchone()
        plan = invoice_write.prepare(
            db,
            AUTH,
            company_id="C001",
            invoice_id="F005",
            patch={"purpose": "办公资料备份"},
            expected_revision=1,
            source_id=ex.source_id,
            source_refs=[{"source_id": ex.source_id, "quote": src["content"]}],
            execution=ex,
        )
        saved = invoice_write.commit(db, AUTH, str(plan["plan_id"]), execution=ex)
        assert saved["commit_state"] == "committed"
        latest = recovery.checkpoint(
            settings.admin_database_url, args.output / "latest-receipt.json"
        )
        snapshot = latest["tables"]
        for table in [
            "operations",
            "write_plans",
            "tasks",
            "preferences",
            "sources",
            "history_embeddings",
            "knowledge_versions",
            "knowledge_files",
            "knowledge_blocks",
            "rule_knowledge_refs",
            "retrieval_embeddings",
            "retrieval_jobs",
            "user_company_grants",
        ]:
            assert snapshot[table]["rows"] > 0, table
        recovery.backup(settings.admin_database_url, args.output / "latest")
        admin.close()
        db.close()
        engine.close()
        rejects(
            "RECOVERY_POINT_BEHIND",
            lambda: recovery.restore(
                settings.admin_database_url,
                args.output / "older",
                args.output / "latest-receipt.json",
                settings,
            ),
        )
        assert recovery.in_maintenance(settings.admin_database_url)
        rejects(
            "RECOVERY_REFERENCE_UNCONFIRMED",
            lambda: recovery.checkpoint(
                settings.admin_database_url, args.output / "bad-new-reference.json"
            ),
        )
        record("old_backup_keeps_maintenance")
        restored = recovery.restore(
            settings.admin_database_url,
            args.output / "latest",
            args.output / "latest-receipt.json",
            settings,
        )
        assert restored["fingerprint"] == latest["fingerprint"] and not recovery.in_maintenance(
            settings.admin_database_url
        )
        with psycopg.connect(settings.admin_database_url, row_factory=dict_row) as conn:
            assert (
                conn.execute(
                    "SELECT status FROM preferences WHERE preference_id=%s",
                    (preference["preference_id"],),
                ).fetchone()["status"]
                == "deleted"
            )
            assert (
                conn.execute(
                    "SELECT status FROM write_plans WHERE plan_id=%s", (plan["plan_id"],)
                ).fetchone()["status"]
                == "consumed"
            )
            assert not conn.execute(
                "SELECT can_read FROM user_company_grants WHERE user_id='U002' AND company_id='C001'"
            ).fetchone()["can_read"]
            assert not conn.execute(
                "SELECT can_read FROM user_company_grants WHERE user_id='U001' AND company_id='C002'"
            ).fetchone()["can_read"]
            assert (
                conn.execute(
                    "SELECT status FROM knowledge_documents WHERE document_id=%s",
                    (private["document_id"],),
                ).fetchone()["status"]
                == "disabled"
            )
        record("full_state_restore", fingerprint=latest["fingerprint"], tables=len(snapshot))
        write(
            args.output / "report.json",
            {
                "records": records,
                "passed": len(records),
                "mode": "real PostgreSQL and process kills; no chat model in fault injection; actual local BGE vectors",
                "code_fingerprint": digest(
                    {
                        p.name: p.read_text(encoding="utf-8")
                        for p in sorted((ROOT / "backend/app").glob("*.py"))
                    }
                ),
            },
        )
    finally:
        admin.close()
        db.close()
        engine.close()


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--output", type=Path, required=True)
    p.add_argument("--ocr-evaluation", type=Path)
    main(p.parse_args())
